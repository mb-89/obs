"""No node_modules is tracked, and no ignored folder is left over from before a move or deletion.

Reader: whoever adds a Node package to the repository, moves one into a package's build, or moves
or deletes a Python package.

A node_modules is installed from its lockfile, never tracked. A folder a package's build replaced
is nothing anything reads any more, and a Python package folder holding nothing but ignored
``__pycache__`` is an import's namespace package that can shadow the package's new home; a
checkout that still holds either is told to delete it.
"""
import subprocess

import pytest
from pathlib import Path

ROOT = Path(__file__).parents[2]
STALE = {
    "adapters/html/maths/node_modules": "adapters/html/hatch_build.py packages math.js into obs_html",
    "src/obs/diagrams/node_modules": "hatch_build.py packages the diagram renderers into obs",
}
"""Each node_modules a package's build replaced, and the build that replaced it."""
MOVED = {
    "src/obs_html": "the adapter moved to adapters/html/src/obs_html, which an empty src/obs_html shadows",
    "src/obs_html_interim": "the interim adapter was deleted",
}
"""Each Python package folder that moved or was deleted, and what became of it."""


def _left(root: Path) -> list[str]:
    """Each leftover folder under ``root``, with why nothing needs it."""
    def bytecode_only(folder: Path) -> bool:
        return folder.is_dir() and all(
            "__pycache__" in path.relative_to(folder).parts for path in folder.rglob("*") if path.is_file())

    return ([f"{root / path}: stale since {owner}; nothing reads it" for path, owner in STALE.items()
             if (root / path).exists()]
            + [f"{root / path}: holds only __pycache__ since {why}" for path, why in MOVED.items()
               if bytecode_only(root / path)])


def test_git_tracks_no_node_modules() -> None:
    listed = subprocess.run(["git", "ls-files", "-z"], cwd=ROOT, capture_output=True, text=True, check=True)
    tracked = sorted({path.split("node_modules/", 1)[0] + "node_modules" for path in listed.stdout.split("\0")
                      if "node_modules" in path.split("/")})

    assert tracked == [], (f"git tracks {', '.join(tracked)}: a node_modules is installed from its lockfile, "
                           "never tracked (test/structure/test_node_modules.py). Remedy: git rm -r --cached it.")


@pytest.mark.parametrize("package", ["src/obs_html", "src/obs_html_interim"])
def test_a_package_folder_holding_only_bytecode_is_named_with_its_remedy(tmp_path, package) -> None:
    (tmp_path / package / "__pycache__").mkdir(parents=True)
    (tmp_path / package / "__pycache__" / "cli.cpython-312.pyc").write_bytes(b"")
    (tmp_path / "src" / "obs" / "__pycache__").mkdir(parents=True)

    assert [line.split(": ", 1)[0] for line in _left(tmp_path)] == [str(tmp_path / package)]
    (tmp_path / package / "cli.py").write_text("", encoding="utf-8")
    assert _left(tmp_path) == []


def test_no_folder_is_left_from_before_its_package_moved_or_its_build_replaced_it() -> None:
    left = _left(ROOT)

    assert left == [], f"{'; '.join(left)} (test/structure/test_node_modules.py). Remedy: delete it."
